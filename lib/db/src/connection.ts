export function postgresOptions(connectionString: string): PoolConfig {
  let url: URL;
  try {
    url = new URL(connectionString);
  } catch {
    throw new Error("Invalid database connection string.");
  }
  if (!["postgres:", "postgresql:"].includes(url.protocol)) {
    throw new Error("A PostgreSQL database connection string is required.");
  }
  if (!/\.supabase\.(co|com)$/i.test(url.hostname)) {
    return { connectionString };
  }
  // pg connection-string SSL parameters override the explicit TLS object.
  // Remove those overrides so Supabase connections cannot disable verification.
  for (const key of ["sslmode", "sslrootcert", "sslcert", "sslkey"]) {
    url.searchParams.delete(key);
  }
  return {
    connectionString: url.toString(),
    ssl: {
      rejectUnauthorized: true,
      ca: [...rootCertificates, SUPABASE_ROOT_CA],
    },
  };
}
